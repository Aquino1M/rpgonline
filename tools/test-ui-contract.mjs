import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const app = await readFile(new URL('../src/App.jsx', import.meta.url), 'utf8')
const css = await readFile(new URL('../src/mobileTabletV2.css', import.meta.url), 'utf8')
const map = await readFile(new URL('../src/ui/WorldMap.jsx', import.meta.url), 'utf8')
const caravans = await readFile(new URL('../src/game/caravans/CaravanManager.js', import.meta.url), 'utf8')

assert.match(app, /function Inventory\([\s\S]*?const activeClass=.*?[\s\S]*?const activeTier=/, 'inventory must scope its active class data')
assert.match(app, /useState\('bag'\)/, 'inventory must open on the backpack view')
assert.match(app, /inventory-tab-hidden/, 'inventory and character must render as separate tabs')
assert.doesNotMatch(app, /E-mail da Conta/, 'the account portal must not request an e-mail')
assert.match(app, /auth-server-fixed">● Asterra Global/, 'the account portal must lock to the global server')
for (const panel of ['inventory','grimoire','quests','guild','trade','attributes','map','settings']) assert.match(app, new RegExp(`closeAnd\\('${panel}'\\)`), `touch menu must open ${panel}`)
assert.doesNotMatch(app, /closeAnd\('travel'\)/, 'touch menu must not expose remote travel')
assert.doesNotMatch(app, /Mira Fixa/, 'touch menu must not expose fixed aim')
assert.match(app, /mobile-dash" onPointerDown=\{press\('dash'\)\}/, 'dodge must invoke the engine immediately')
assert.match(app, /mobile-run[^\n]*onPointerDown=\{startHold\('setMobileRun'\)\}/, 'run must use hold-to-run')
assert.match(css, /\.app\.touch-ui \.window-inventory \.inventory-rpg/, 'tablet inventory layout override must be loaded last')
assert.match(app, /Classes Despertas[\s\S]*?unlockedClasses\.map/, 'grimoire must list only awakened classes')
assert.doesNotMatch(app, /Coleção de Almas/, 'grimoire must not show the locked-class counter')
assert.match(map, /Marcar local/, 'map must allow a manual destination')
assert.doesNotMatch(map, /Portais e Masmorras/, 'map must not duplicate portal cards beside the map')
assert.match(caravans, /maxActiveCaravans/, 'caravans must have an active cap')
assert.match(caravans, /this\.caravans\.length\) return/, 'caravan initialization must be idempotent')
console.log('ui contract: ok')
